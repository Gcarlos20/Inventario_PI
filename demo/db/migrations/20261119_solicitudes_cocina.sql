-- Adaptación aditiva al esquema de solicitudes que ya existe en Supabase.
-- Conserva SOLICITUDES_COCINA y sus detalles; agrega producto por línea e IDs automáticos.
ALTER TABLE public."DETALLE_SOLICITUD_COCINA"
    ADD COLUMN IF NOT EXISTS "Id_Producto" bigint;

-- Los detalles históricos heredan el producto que antes se guardaba en la cabecera.
UPDATE public."DETALLE_SOLICITUD_COCINA" d
SET "Id_Producto" = s."Id_Producto"
FROM public."SOLICITUDES_COCINA" s
WHERE d.id_solicitud_cocina = s."Id_Solicitud"
  AND d."Id_Producto" IS NULL
  AND s."Id_Producto" IS NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'DETALLE_SOLICITUD_COCINA_Id_Producto_fkey'
          AND conrelid = 'public."DETALLE_SOLICITUD_COCINA"'::regclass
    ) THEN
        ALTER TABLE public."DETALLE_SOLICITUD_COCINA"
            ADD CONSTRAINT "DETALLE_SOLICITUD_COCINA_Id_Producto_fkey"
            FOREIGN KEY ("Id_Producto") REFERENCES public."PRODUCTOS" ("Id_Producto") ON DELETE RESTRICT;
    END IF;
END $$;

-- Las tablas actuales no tienen default para estas claves; sincroniza secuencias
-- respetando los identificadores históricos.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'SOLICITUDES_COCINA'
          AND column_name = 'Id_Solicitud' AND is_identity = 'YES'
    ) THEN
        ALTER TABLE public."SOLICITUDES_COCINA"
            ALTER COLUMN "Id_Solicitud" ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'DETALLE_SOLICITUD_COCINA'
          AND column_name = 'Id_Detalle' AND is_identity = 'YES'
    ) THEN
        ALTER TABLE public."DETALLE_SOLICITUD_COCINA"
            ALTER COLUMN "Id_Detalle" ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;

SELECT setval(pg_get_serial_sequence('public."SOLICITUDES_COCINA"', 'Id_Solicitud'),
              GREATEST(COALESCE((SELECT MAX("Id_Solicitud") FROM public."SOLICITUDES_COCINA"), 0) + 1, 1), false);
SELECT setval(pg_get_serial_sequence('public."DETALLE_SOLICITUD_COCINA"', 'Id_Detalle'),
              GREATEST(COALESCE((SELECT MAX("Id_Detalle") FROM public."DETALLE_SOLICITUD_COCINA"), 0) + 1, 1), false);

