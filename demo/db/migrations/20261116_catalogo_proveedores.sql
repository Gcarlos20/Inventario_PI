-- Ejecutar una sola vez desde el SQL Editor de Supabase.
ALTER TABLE public."PROVEEDORES"
    ADD COLUMN IF NOT EXISTS "NIT" text,
    ADD COLUMN IF NOT EXISTS "Nombre_Contacto" text,
    ADD COLUMN IF NOT EXISTS "Telefono" text,
    ADD COLUMN IF NOT EXISTS "Correo" text,
    ADD COLUMN IF NOT EXISTS "Direccion" text,
    ADD COLUMN IF NOT EXISTS "Ciudad" text,
    ADD COLUMN IF NOT EXISTS "Tipo_Proveedor" text DEFAULT 'Producto',
    ADD COLUMN IF NOT EXISTS "Estado" text NOT NULL DEFAULT 'Activo',
    ADD COLUMN IF NOT EXISTS "Fecha_Registro" date NOT NULL DEFAULT CURRENT_DATE,
    ADD COLUMN IF NOT EXISTS "Observacion" text;

CREATE TABLE IF NOT EXISTS public."PROVEEDOR_CATALOGO" (
    "Id_Oferta" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Id_Proveedores" integer NOT NULL REFERENCES public."PROVEEDORES" ("Id_Proveedores") ON DELETE CASCADE,
    "Nombre" text NOT NULL,
    "Tipo" text NOT NULL DEFAULT 'Producto',
    "Descripcion" text,
    "Precio_Referencia" numeric(12, 2),
    CONSTRAINT "PROVEEDOR_CATALOGO_Precio_no_negativo"
        CHECK ("Precio_Referencia" IS NULL OR "Precio_Referencia" >= 0)
);

CREATE INDEX IF NOT EXISTS "idx_proveedor_catalogo_proveedor"
    ON public."PROVEEDOR_CATALOGO" ("Id_Proveedores");
